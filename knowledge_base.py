PROCUREMENT_RULES = """
مبادئ نظام المشتريات الحكومية والمنافسات:
- يجب وجود ضمان ابتدائي ونهائي واضح للعقود ذات القيمة العالية
- يجب تحديد آلية وشروط فسخ العقد بشكل متوازن بين الطرفين
- الغرامات التأخيرية يجب أن تكون معقولة ومحددة بحد أقصى (عادة لا تتجاوز نسبة معينة من قيمة العقد)
- يجب النص على آلية تسوية النزاعات (تحكيم أو القضاء المختص)
- يجب توثيق مواصفات فنية واضحة وقابلة للقياس للسلع أو الخدمات محل التعاقد
- يجب وجود بند لحالات القوة القاهرة يُعفي الأطراف من المسؤولية في ظروف استثنائية
- يُفضّل وجود آلية فحص واستلام رسمية قبل اعتماد التوريد النهائي
"""

HUMANITARIAN_RULES = """
معايير Sphere الإنسانية للمشتريات والتوريد الإغاثي:
- مراجعة كل البنود التقنية للمواد الإغاثية (مطابقة المواصفات، الجودة، السلامة)
- التحقق من تواريخ صلاحية الشهادات والمنتجات القابلة للتلف
- استبعاد أي مواد خطرة أو مسرطنة أو غير مطابقة للمعايير الصحية
- مطابقة الكميات المذكورة في العقد مع الاحتياج الفعلي المعلن
- يجب توفر شهادات جودة وفحص مختبري مستقلة قبل الاستلام
- الشفافية في التسعير ومنع تضارب المصالح مع الجهات المستفيدة
"""

LABOR_RULES = """
مبادئ نظام العمل السعودي (للعقود التي تتضمن عمالة أو خدمات بشرية):
- يجب تحديد الأجر وموعد الصرف بوضوح
- يجب النص على ساعات العمل والإجازات المستحقة
- لا يجوز فرض شروط تعسفية للفصل أو إنهاء الخدمة دون إشعار كافٍ
- يجب توضيح التأمينات الاجتماعية والتأمين الطبي إن وجد
- يجب مراعاة نظام التوطين (السعودة) حيثما ينطبق على طبيعة العقد
- يُحظر أي بند يخالف الحد الأدنى لحقوق العامل المقررة نظاماً
"""

COMMERCIAL_RULES = """
مبادئ قانونية تجارية عامة (تنطبق على معظم أنواع العقود):
- يجب تحديد أطراف العقد بوضوح (الاسم القانوني الكامل، السجل التجاري إن وجد)
- يجب تحديد محل العقد وموضوعه بدقة دون غموض
- الأسعار وشروط الدفع يجب أن تكون واضحة (المبلغ، العملة، الجدولة، الضمانات المالية)
- عدم التوازن الشديد بين حقوق والتزامات الطرفين قد يُعتبر شرطاً تعسفياً
- يجب تحديد القانون الواجب التطبيق والجهة القضائية أو التحكيمية المختصة
- يُفضّل وجود بند سرية يحمي المعلومات التجارية الحساسة لأي من الطرفين
- مدة العقد وآلية التجديد أو الإنهاء يجب أن تكون صريحة
"""

MOC_RULES = """
أنظمة وزارة التجارة السعودية ذات الصلة (مصدر رسمي: البوابة الوطنية للتشريعات laws.boe.gov.sa):

1) نظام الشركات (الصادر بالمرسوم الملكي رقم م/132 وتاريخ 1443/12/1هـ):
   - يجب أن يكون للشركة عقد تأسيس أو نظام أساسي واضح يحدد الشكل القانوني (تضامن، محدودة، مساهمة، مساهمة مبسطة... إلخ)
   - الاسم التجاري للطرف المتعاقد يجب أن يكون مطابقاً للسجل التجاري ولا يخالف نظام الأسماء التجارية
   - يجب مراعاة قواعد حوكمة الشركات (خاصة شركات المساهمة المدرجة) عند التعاقد نيابة عن الشركة
   - من يوقّع العقد نيابة عن الشركة يجب أن يملك تفويضاً أو صلاحية نظامية موثقة (تفويض تجاري)

2) نظام مكافحة التستر التجاري (الصادر بالمرسوم الملكي رقم م/4 وتاريخ 1442/1/1هـ):
   - يُحظر تمكين غير السعودي من ممارسة نشاط اقتصادي مرخّص لسعودي دون ترخيص نظامي (التستر التجاري)
   - يجب التحقق من أن المورد/المقاول مرخّص فعلياً لممارسة النشاط محل العقد وأن الترخيص باسمه الحقيقي
   - أي بند يمنح طرفاً أجنبياً غير مرخّص له سيطرة فعلية على إيرادات أو إدارة المنشأة السعودية يُعد مؤشر خطر جسيم (قد يشكل جريمة تستر تجاري، وعقوبتها تصل للسجن والغرامة وشطب السجل التجاري)

3) نظام مكافحة الغش التجاري:
   - يُحظر بيع أو التعاقد على سلع فاسدة أو منتهية الصلاحية أو غير مطابقة للبيانات المعلنة عنها
   - يجب الإفصاح الصحيح عن بلد المنشأ وتاريخ الصلاحية ومطابقة الوصف للسلعة الفعلية
   - السلع الخاضعة لمواصفات إلزامية يجب أن تحمل علامة المطابقة السعودية (SASO) عند الاقتضاء

4) نظام التجارة الإلكترونية وحماية المستهلك (للعقود التي تتضمن بيعاً أو خدمة عبر منصات رقمية):
   - إلزامية الإفصاح عن هوية التاجر وبياناته التجارية ووسائل التواصل
   - يجب توضيح سياسة الاسترجاع والاستبدال وحق الإلغاء للمستهلك
   - يُحظر استخدام إعلانات أو أوصاف مضلّلة للمنتج أو الخدمة
   - يجب استخدام بوابات دفع إلكتروني مرخّصة من البنك المركزي السعودي (ساما) فقط، ويُحظر قبول مدفوعات عبر حسابات شخصية غير موثقة
"""

RULES_BY_TYPE = {
    "supply": [PROCUREMENT_RULES, COMMERCIAL_RULES, MOC_RULES],
    "service": [COMMERCIAL_RULES, MOC_RULES],
    "construction": [PROCUREMENT_RULES, COMMERCIAL_RULES, MOC_RULES],
    "franchise": [COMMERCIAL_RULES, MOC_RULES],
    "employment": [LABOR_RULES, COMMERCIAL_RULES, MOC_RULES],
    "technology": [COMMERCIAL_RULES, MOC_RULES],
    "partnership": [COMMERCIAL_RULES, MOC_RULES],
    "humanitarian": [HUMANITARIAN_RULES, PROCUREMENT_RULES, COMMERCIAL_RULES, MOC_RULES],
}


INDIVIDUAL_LABOR_SIGNALS = [
    "الأجير", "أجير", "الموظف", "راتب شهري", "مكافأة نهاية الخدمة",
    "إجازة سنوية", "صاحب العمل", "ساعات العمل اليومية"
]


def get_context_for_type(contract_type, text=None):
    """يرجع نص المبادئ التنظيمية المرتبطة بنوع العقد، مع القواعد التجارية وقواعد وزارة التجارة دائماً.
    لو النص فيه مؤشرات توظيف فردي واضحة (حتى لو صُنّف العقد كـ 'service')، تُضاف قواعد نظام العمل احتياطياً."""
    rules = list(RULES_BY_TYPE.get(contract_type, [COMMERCIAL_RULES, MOC_RULES]))

    if contract_type == "service" and text:
        if any(signal in text for signal in INDIVIDUAL_LABOR_SIGNALS):
            rules.append(LABOR_RULES)

    # تأكد من وجود القواعد التجارية وقواعد وزارة التجارة دائماً (احتياطي)
    for mandatory_rule in (COMMERCIAL_RULES, MOC_RULES):
        if mandatory_rule not in rules:
            rules = rules + [mandatory_rule]
    return "\n".join(rules)
